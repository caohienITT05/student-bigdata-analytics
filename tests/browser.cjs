const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

(async () => {
    const reports = path.resolve(__dirname, '../reports/data_pipeline');
    const browser = await chromium.launch({headless:true, channel:'msedge'});
    const page = await browser.newPage({viewport:{width:1360,height:900}});
    const errors=[], checks=[], removedRequests=[];
    page.on('request',r=>{if(/\/api\/multi\/(academic|oulad)\/table|[?&](scope|labels|kind)=/.test(r.url()))removedRequests.push(r.url());});
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',e=>{if(e.type()==='error')errors.push(e.text());});
    const names={overview:'Tổng quan',academic:'Kết quả học tập',oulad:'Hành vi OULAD',prediction:'Dự đoán & tra cứu',quality:'Chất lượng dữ liệu'};
    const panel=k=>page.locator('#panel-'+k);
    const pass=s=>{checks.push(s);console.log('PASS',s);};
    const api=async url=>{const res=await page.request.get('http://127.0.0.1:8000/api/'+url);assert.equal(res.status(),200);return res.json();};
    const go=async k=>{
        await page.getByRole('tab',{name:names[k],exact:true}).click();
        await page.waitForURL('**/dashboard#'+k);
        await panel(k).waitFor({state:'visible'});
        assert.equal(await page.locator('[role="tabpanel"]:visible').count(),1);
        assert.equal(await page.getByRole('tab',{selected:true}).innerText(),names[k]);
        assert.equal(await page.evaluate(()=>scrollY),0);
    };
    const chart=async title=>{
        await page.waitForFunction(title=>{const el=[...document.querySelectorAll('canvas')].find(e=>e.getAttribute('aria-label')===title);const c=el&&Chart.getChart(el);return c&&c.width>0&&c.height>0;},title);
        return page.getByRole('img',{name:title,exact:true}).evaluate(el=>Chart.getChart(el).data.datasets.flatMap(d=>d.data).reduce((a,b)=>a+b,0));
    };
    const details=(k,title)=>panel(k).locator('details').filter({has:page.locator('summary',{hasText:title})});
    const snap=k=>page.screenshot({path:path.join(reports,'catalog-'+k+'.png'),fullPage:true});
    try {
        await page.goto('http://127.0.0.1:8000/dashboard',{waitUntil:'networkidle',timeout:60000});
        assert.deepEqual(await page.getByRole('tab').allTextContents(),Object.values(names));
        assert.equal(await page.locator('[role="tabpanel"]:visible').count(),1);
        await panel('overview').getByText('127.530',{exact:true}).waitFor();
        assert.equal(await panel('overview').locator('canvas,table').count(),0);
        await snap('overview');pass('Five navigation items; source-separated overview without detail duplication');
        const academic=await api('multi/academic/summary'), status=await api('multi/status');
        await panel('overview').getByRole('button',{name:'Mở kết quả học tập →',exact:true}).click();
        await page.waitForURL('**/dashboard#academic');
        assert.equal(await chart('Phân bố Target theo nguồn'),academic.totals.records);
        assert.equal(await panel('academic').locator('select').count(),1);
        assert.equal(await panel('academic').locator('details').count(),0);
        await snap('academic');pass('Academic source filter and four charts retained; detailed tables and extra filters removed');
        await page.getByLabel('Nguồn nhánh A').selectOption('kaggle_test');
        await panel('academic').getByText('51.012',{exact:true}).first().waitFor();
        await go('quality');await go('academic');
        assert.equal(await page.getByLabel('Nguồn nhánh A').inputValue(),'kaggle_test');
        assert.equal(await chart('Phân bố Target theo nguồn'),academic.totals.unlabelled);
        pass('Source filter retained and Kaggle test stays unlabeled');
        await page.reload({waitUntil:'networkidle'});await panel('academic').waitFor({state:'visible'});await chart('Phân bố Target theo nguồn');
        pass('URL hash restores section on reload');
        await go('oulad');
        assert.equal(await panel('oulad').locator('select').count(),2);
        assert.equal(await panel('oulad').locator('details').count(),1);
        await panel('oulad').getByText('Phạm vi: cả học phần.',{exact:false}).waitFor();
        const full=await api('multi/oulad/summary');
        assert.equal(await chart('Hoạt động theo tuần và nhóm kết quả về sau'),full.weekly.reduce((s,r)=>s+r.clicks,0));
        await page.getByLabel('Học phần OULAD').selectOption('AAA');await page.getByLabel('Đợt học OULAD').selectOption('2013J');
        const filtered=await api('multi/oulad/summary?module=AAA&presentation=2013J');
        await panel('oulad').getByText(new Intl.NumberFormat('vi-VN').format(filtered.population.enrolments),{exact:true}).first().waitFor();
        await go('overview');await go('oulad');
        assert.equal(await page.getByLabel('Học phần OULAD').inputValue(),'AAA');
        assert.equal(await page.getByLabel('Đợt học OULAD').inputValue(),'2013J');
        assert.equal(await chart('Hoạt động theo tuần và nhóm kết quả về sau'),filtered.weekly.reduce((s,r)=>s+r.clicks,0));
        await snap('oulad');pass('Full-course OULAD filters and chart data/dimensions preserved; assessment and early analysis removed');
        await page.evaluate(()=>scrollTo(0,document.documentElement.scrollHeight));
        assert.equal(await page.locator('[data-dashboard-header]').evaluate(el=>Math.round(el.getBoundingClientRect().top)),0);
        pass('Navigation remains sticky');
        await go('prediction');const old=await api('stats');assert.equal(await chart('Phân bố dự đoán của mô hình'),old.total_students);
        const search=page.getByPlaceholder('Tìm mã SV...');
        let response=page.waitForResponse(r=>r.url().includes('/api/students?')&&r.url().includes('23010001'));
        await search.fill('23010001');const students=await(await response).json();await panel('prediction').getByText('23010001',{exact:true}).waitFor();
        const cells=await panel('prediction').locator('tbody tr').first().locator('td').allTextContents();
        assert.equal(cells[5],students[0].Target);assert.equal(cells[6],students[0].Predicted_Target);
        response=page.waitForResponse(r=>r.url().endsWith('/api/predict')&&r.request().method()==='POST');
        await page.getByRole('button',{name:'Chạy Dự Đoán',exact:true}).click();const prediction=await(await response).json();
        await panel('prediction').getByText('Dự đoán: '+prediction.prediction,{exact:true}).waitFor();
        await go('academic');await go('prediction');assert.equal(await search.inputValue(),'23010001');
        await panel('prediction').getByText('Dự đoán: '+prediction.prediction,{exact:true}).waitFor();
        response=page.waitForResponse(r=>r.url().includes('/api/students?')&&r.url().includes('search=&'));
        await search.fill('');await response;
        await panel('prediction').getByRole('button',{name:'Trang sau',exact:true}).click();await panel('prediction').getByText(/trang 2\//).waitFor();
        assert.equal(await panel('prediction').locator('tbody tr').count(),20);
        response=page.waitForResponse(r=>r.url().includes('risk_only=true'));await page.getByRole('button',{name:'Lọc SV nguy cơ thôi học',exact:true}).click();
        assert((await(await response).json()).every(r=>r.Predicted_Target==='Dropout'));await panel('prediction').getByText(/trang 1\//).waitFor();
        await snap('prediction');pass('Existing prediction/search/risk API, separate Target column, pagination and state retained');
        await go('quality');const q=panel('quality');
        assert.equal(await q.locator('select').count(),2);
        assert.equal(await q.locator('details').count(),2);
        assert.equal(await q.getByRole('heading',{name:'Báo cáo nguồn và kiểm chứng',exact:true}).count(),0);
        const explorer=q.getByRole('region',{name:'Khám phá dữ liệu sử dụng',exact:true});
        await explorer.getByRole('table',{name:'Các trường trong dữ liệu',exact:true}).waitFor();
        await explorer.getByText('4.424 dòng · 35 cột',{exact:true}).waitFor();
        await explorer.getByRole('button',{name:'Trang sau',exact:true}).click();
        await explorer.getByText('35 trường · trang 2/5',{exact:true}).waitFor();
        await explorer.getByRole('button',{name:/Kaggle/}).click();
        await explorer.getByLabel('File dữ liệu',{exact:true}).selectOption('test');
        await explorer.getByText('51.012 dòng · 37 cột',{exact:true}).waitFor();
        await explorer.getByRole('button',{name:/OULAD/}).click();
        await explorer.getByLabel('File dữ liệu',{exact:true}).selectOption('studentVle');
        await explorer.getByText('10.655.280 dòng · 6 cột',{exact:true}).waitFor();
        assert.equal(await explorer.locator('tbody tr').count(),6);
        await explorer.getByLabel('File dữ liệu',{exact:true}).selectOption('studentInfo');
        await explorer.getByLabel('Nhóm thông tin',{exact:true}).selectOption('person');
        assert.equal(await explorer.locator('tbody tr').count(),6);
        await go('overview');await go('quality');
        assert.equal(await explorer.getByLabel('File dữ liệu',{exact:true}).inputValue(),'studentInfo');
        assert.equal(await explorer.getByLabel('Nhóm thông tin',{exact:true}).inputValue(),'person');
        pass('Source explorer: original/Kaggle/OULAD, file and group filters, pagination and state retention');
        const quality=details('quality','Chất lượng theo nguồn và file');
        assert.equal(await quality.getAttribute('open'),null);
        await quality.locator('summary').click();
        const technical=details('quality','Chi tiết kỹ thuật');
        assert.equal(await technical.getAttribute('open'),null);
        assert.equal(await q.getByRole('heading',{name:'Kiểm tra JOIN',exact:true}).isVisible(),false);
        await technical.locator('summary').click();
        await technical.getByText('10.655.280',{exact:true}).first().waitFor();
        await technical.getByText(status.metadata.database,{exact:true}).waitFor();
        await technical.getByRole('button',{name:'Trang sau',exact:true}).first().click();
        await technical.getByText(/trang 2\//).waitFor();
        await quality.getByRole('button',{name:'Trang sau',exact:true}).click();
        await quality.getByText(/trang 2\//).waitFor();
        for(const link of await q.getByRole('link').all())assert.equal((await page.request.get('http://127.0.0.1:8000'+await link.getAttribute('href'))).status(),200);
        await go('overview');await go('quality');
        assert.notEqual(await technical.getAttribute('open'),null);
        await snap('quality');pass('Source quality pagination and collapsed JOIN/Spark details retained; removed report links stay absent');
        await page.reload({waitUntil:'networkidle'});await panel('quality').waitFor({state:'visible'});
        await page.goBack();await panel('overview').waitFor({state:'visible'});await page.goForward();await panel('quality').waitFor({state:'visible'});
        pass('Hash reload and browser back/forward');
        await page.setViewportSize({width:390,height:844});
        for(const k of Object.keys(names)){
            await go(k);await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth+1,null,{timeout:5000});
            if(k==='academic')await chart('Phân bố Target theo nguồn');if(k==='oulad')await chart('Hoạt động theo tuần và nhóm kết quả về sau');if(k==='prediction')await chart('Phân bố dự đoán của mô hình');
            await snap('mobile-'+k);
        }
        assert(await page.getByRole('navigation',{name:'Điều hướng dashboard'}).evaluate(el=>el.scrollWidth>el.clientWidth));
        pass('Five mobile sections fit width; horizontal navigation and responsive charts');
        assert.deepEqual(removedRequests,[]);pass('Frontend sends no requests for removed routes or filters');
        assert.deepEqual(errors,[]);pass('No browser console/page errors');
        await fs.writeFile(path.join(reports,'catalog_browser_verification.json'),JSON.stringify({at:new Date().toISOString(),browser:'Edge/Chromium headless',checks,errors},null,2));
    }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
